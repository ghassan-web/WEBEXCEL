import sys
from collections import defaultdict
from pathlib import Path

from dotenv import load_dotenv
from fastapi import HTTPException
from sqlalchemy import text

BACKEND_DIR = Path(__file__).resolve().parents[1]
load_dotenv(BACKEND_DIR / ".env")
sys.path.insert(0, str(BACKEND_DIR))

from app.models.database import engine
from app.services.cedant_result_schema import (
    REQUIRED_FOREIGN_KEYS,
    RESULT_METADATA_COLUMNS,
    RESULT_METADATA_TYPES,
    result_table_name,
    sql_type_for_field,
)


def _result_table_name(short_name: str) -> str:
    try:
        return result_table_name(short_name)
    except HTTPException as exc:
        raise ValueError(str(exc.detail)) from exc


def _sql_type(data_type: str) -> tuple[str, set[str]]:
    try:
        return sql_type_for_field(data_type)
    except HTTPException as exc:
        raise ValueError(str(exc.detail)) from exc


def _result_plans(conn) -> dict[str, dict]:
    rows = conn.execute(
        text(
            "SELECT DISTINCT ON (m.cedant_code, f.field_id) "
            "c.cedant_code, c.cedant_short_name, f.field_name, "
            "f.data_type, m.header_name "
            "FROM rekonsiliasi.master_mapping_column m "
            "JOIN rekonsiliasi.master_field f ON f.field_id = m.field_id "
            "JOIN rekonsiliasi.master_oscedant_code c ON c.cedant_code = m.cedant_code "
            "WHERE UPPER(BTRIM(f.dataset_type)) = 'OS CEDANT' "
            "AND f.default_source = 'column' "
            "AND m.header_name IS NOT NULL "
            "ORDER BY m.cedant_code, f.field_id, m.mapping_version ASC, "
            "m.column_index ASC NULLS LAST, m.mapping_id ASC"
        )
    ).mappings()
    plans: dict[str, dict] = {}
    for row in rows:
        table_name = _result_table_name(row["cedant_short_name"])
        plan = plans.setdefault(table_name, {"cedant_codes": set(), "columns": {}})
        plan["cedant_codes"].add(row["cedant_code"])
        field_name = row["field_name"]
        header = row["header_name"]
        if field_name == "class_code":
            continue
        if not header:
            continue
        if len(header) > 63:
            raise ValueError(f"Header melebihi batas identifier PostgreSQL: {header!r}")
        if header.casefold() in {name.casefold() for name in RESULT_METADATA_COLUMNS}:
            raise ValueError(f"Header sumber bentrok dengan metadata tabel hasil: {header!r}")
        sql_type, compatible_types = _sql_type(row["data_type"])
        existing = plan["columns"].get(header)
        if existing and existing["sql_type"] != sql_type:
            raise ValueError(
                f"Header {header!r} dipetakan ke tipe yang berbeda pada {table_name}."
            )
        plan["columns"][header] = {
            "sql_type": sql_type,
            "compatible_types": compatible_types,
        }
    return plans


def _quoted_table(conn, table_name: str) -> str:
    preparer = conn.dialect.identifier_preparer
    return f"{preparer.quote_schema('hasil_rekonsiliasi')}.{preparer.quote(table_name)}"


def _table_columns(conn, table_name: str) -> dict[str, dict]:
    rows = conn.execute(
        text(
            "SELECT column_name, udt_name, is_nullable, is_identity, column_default "
            "FROM information_schema.columns "
            "WHERE table_schema = 'hasil_rekonsiliasi' AND table_name = :table_name"
        ),
        {"table_name": table_name},
    ).mappings()
    return {row["column_name"]: dict(row) for row in rows}


def _create_result_table(conn, table_name: str, plan: dict) -> None:
    preparer = conn.dialect.identifier_preparer
    q = preparer.quote
    constraints = [
        f"CONSTRAINT {q(f'fk_{table_name[:40]}_cedant')} "
        "FOREIGN KEY (cedant_code) "
        "REFERENCES rekonsiliasi.master_oscedant_code (cedant_code)",
        f"CONSTRAINT {q(f'fk_{table_name[:40]}_upload')} "
        "FOREIGN KEY (upload_table_id) "
        "REFERENCES rekonsiliasi.upload_table (table_id)",
        f"CONSTRAINT {q(f'uq_{table_name[:44]}_upload_row')} "
        "UNIQUE (upload_table_id, excel_row_number)",
    ]
    columns = [
        '"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
        '"cedant_code" VARCHAR(50) NOT NULL',
        '"class_code" VARCHAR(50)',
        '"upload_table_id" BIGINT NOT NULL',
        '"excel_row_number" INTEGER NOT NULL',
    ]
    columns.extend(
        f"{q(header)} {details['sql_type']}"
        for header, details in plan["columns"].items()
    )
    columns.extend(
        [
            '"reporting_month" INTEGER NOT NULL',
            '"reporting_year" INTEGER NOT NULL',
            '"file_name" TEXT NOT NULL',
            '"sheet_name" TEXT NOT NULL',
            '"created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP',
        ]
    )
    conn.exec_driver_sql(
        f"CREATE TABLE {_quoted_table(conn, table_name)} "
        f"({', '.join(columns + constraints)})"
    )


def _unique_constraints(conn, table_name: str) -> list[set[str]]:
    rows = conn.execute(
        text(
            "SELECT tc.constraint_name, kcu.column_name, kcu.ordinal_position "
            "FROM information_schema.table_constraints tc "
            "JOIN information_schema.key_column_usage kcu "
            "ON tc.constraint_schema = kcu.constraint_schema "
            "AND tc.table_name = kcu.table_name "
            "AND tc.constraint_name = kcu.constraint_name "
            "WHERE tc.table_schema = 'hasil_rekonsiliasi' "
            "AND tc.table_name = :table_name AND tc.constraint_type = 'UNIQUE' "
            "ORDER BY tc.constraint_name, kcu.ordinal_position"
        ),
        {"table_name": table_name},
    ).mappings()
    by_name: dict[str, list[str]] = defaultdict(list)
    for row in rows:
        by_name[row["constraint_name"]].append(row["column_name"])
    return [set(columns) for columns in by_name.values() if len(columns) == 2]


def _foreign_keys(conn, table_name: str) -> set[tuple[str, str, str, str]]:
    rows = conn.execute(
        text(
            "SELECT source_column.attname, target_schema.nspname, target_table.relname, "
            "target_column.attname "
            "FROM pg_constraint constraint_row "
            "JOIN pg_class source_table ON source_table.oid = constraint_row.conrelid "
            "JOIN pg_namespace source_schema ON source_schema.oid = source_table.relnamespace "
            "JOIN pg_class target_table ON target_table.oid = constraint_row.confrelid "
            "JOIN pg_namespace target_schema ON target_schema.oid = target_table.relnamespace "
            "JOIN LATERAL unnest(constraint_row.conkey) WITH ORDINALITY "
            "AS source_key(attnum, ordinal) ON TRUE "
            "JOIN pg_attribute source_column ON source_column.attrelid = source_table.oid "
            "AND source_column.attnum = source_key.attnum "
            "JOIN LATERAL unnest(constraint_row.confkey) WITH ORDINALITY "
            "AS target_key(attnum, ordinal) ON target_key.ordinal = source_key.ordinal "
            "JOIN pg_attribute target_column ON target_column.attrelid = target_table.oid "
            "AND target_column.attnum = target_key.attnum "
            "WHERE constraint_row.contype = 'f' "
            "AND source_schema.nspname = 'hasil_rekonsiliasi' "
            "AND source_table.relname = :table_name"
        ),
        {"table_name": table_name},
    )
    return {tuple(row) for row in rows}


def _ensure_result_table(conn, table_name: str, plan: dict, apply: bool) -> list[str]:
    exists = conn.execute(
        text(
            "SELECT EXISTS (SELECT 1 FROM information_schema.tables "
            "WHERE table_schema = 'hasil_rekonsiliasi' AND table_name = :table_name)"
        ),
        {"table_name": table_name},
    ).scalar_one()
    changes = []
    if not exists:
        if not apply:
            return ["buat tabel hasil"]
        _create_result_table(conn, table_name, plan)
        changes.append("buat tabel hasil")

    columns = _table_columns(conn, table_name)
    missing_metadata = RESULT_METADATA_COLUMNS - columns.keys()
    if missing_metadata:
        raise ValueError(
            f"hasil_rekonsiliasi.{table_name} tidak memiliki metadata wajib: "
            + ", ".join(sorted(missing_metadata))
        )

    for name, expected_udt in RESULT_METADATA_TYPES.items():
        if columns[name]["udt_name"] != expected_udt:
            raise ValueError(
                f"Jenis kolom metadata {table_name}.{name} tidak cocok: "
                f"{columns[name]['udt_name']} (harus {expected_udt})."
            )
    required_non_null = RESULT_METADATA_COLUMNS - {"class_code"}
    nullable_metadata = [
        name for name in required_non_null if columns[name]["is_nullable"] != "NO"
    ]
    if nullable_metadata:
        raise ValueError(
            f"Metadata wajib nullable pada hasil_rekonsiliasi.{table_name}: "
            + ", ".join(sorted(nullable_metadata))
        )
    if (
        columns["id"]["is_identity"] != "YES"
        and not columns["id"]["column_default"]
    ):
        raise ValueError(
            f"hasil_rekonsiliasi.{table_name}.id tidak memiliki generator ID."
        )
    if not columns["created_at"]["column_default"]:
        raise ValueError(
            f"hasil_rekonsiliasi.{table_name}.created_at tidak memiliki default timestamp."
        )

    for header, details in plan["columns"].items():
        column = columns.get(header)
        if column is None:
            if not apply:
                changes.append(f"tambah kolom sumber {header}")
                continue
            conn.exec_driver_sql(
                f"ALTER TABLE {_quoted_table(conn, table_name)} "
                f"ADD COLUMN {conn.dialect.identifier_preparer.quote(header)} "
                f"{details['sql_type']}"
            )
            changes.append(f"tambah kolom sumber {header}")
        elif column["udt_name"] not in details["compatible_types"]:
            raise ValueError(
                f"Jenis kolom hasil {table_name}.{header} tidak cocok: "
                f"{column['udt_name']} (harus {details['sql_type']})."
            )

    unique_pair = {"upload_table_id", "excel_row_number"}
    if unique_pair not in _unique_constraints(conn, table_name):
        if not apply:
            changes.append("tambahkan unique upload_table_id + excel_row_number")
        else:
            duplicate = conn.execute(
                text(
                    f"SELECT 1 FROM {_quoted_table(conn, table_name)} "
                    "GROUP BY upload_table_id, excel_row_number "
                    "HAVING COUNT(*) > 1 LIMIT 1"
                )
            ).first()
            if duplicate:
                raise ValueError(
                    f"hasil_rekonsiliasi.{table_name} memiliki duplikat pasangan "
                    "(upload_table_id, excel_row_number); unique constraint tidak ditambahkan."
                )
            constraint = f"uq_{table_name[:44]}_upload_row"
            conn.exec_driver_sql(
                f"ALTER TABLE {_quoted_table(conn, table_name)} "
                f"ADD CONSTRAINT {conn.dialect.identifier_preparer.quote(constraint)} "
                "UNIQUE (upload_table_id, excel_row_number)"
            )
            changes.append("tambahkan unique upload_table_id + excel_row_number")

    missing_fks = REQUIRED_FOREIGN_KEYS - _foreign_keys(conn, table_name)
    if missing_fks:
        raise ValueError(
            f"hasil_rekonsiliasi.{table_name} belum memiliki foreign key provenance: "
            + ", ".join(f"{item[0]}->{item[1]}.{item[2]}.{item[3]}" for item in sorted(missing_fks))
        )
    return changes


def run(apply: bool) -> bool:
    changes = []
    with engine.begin() as conn:
        schema_exists = conn.execute(
            text("SELECT EXISTS (SELECT 1 FROM information_schema.schemata WHERE schema_name = 'hasil_rekonsiliasi')")
        ).scalar_one()
        if not schema_exists:
            raise ValueError(
                "Schema hasil_rekonsiliasi belum ada; script tidak membuat schema."
            )

        plans = _result_plans(conn)
        for table_name, plan in plans.items():
            table_changes = _ensure_result_table(conn, table_name, plan, apply)
            changes.extend(
                f"hasil_rekonsiliasi.{table_name}: {change}"
                for change in table_changes
            )

    if changes:
        for change in changes:
            print(("APPLIED: " if apply else "REQUIRED: ") + change)
    else:
        print("Point 2/3 upload support schema and catalog are consistent.")
    if not plans:
        print("No active OS Cedant mappings require per-cedant result tables.")
    return not changes or apply


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Audit/provision Point 2-3 upload support without changing core table schemas."
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--apply",
        action="store_true",
        help="Provision mapped OS result tables and source columns only.",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="Audit without changing database objects (default).",
    )
    args = parser.parse_args()
    try:
        return 0 if run(args.apply) else 1
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
